export function locationFor(district, community, index = 0) {
  const exact = communityLocations[community]
  if (exact) return { lat: exact[0], lng: exact[1], verifiedTo: '小区/街镇' }
  const center = districtCenters[district] || [30.2741, 120.1551]
  const angle = index * 2.39996
  return {
    lat: Number((center[0] + Math.sin(angle) * 0.018).toFixed(6)),
    lng: Number((center[1] + Math.cos(angle) * 0.022).toFixed(6)),
    verifiedTo: '区县范围'
  }
}
